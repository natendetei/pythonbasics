# A module is a python file that contains reusable code.
# Built-in modules math, random.

# Math module.
import math
import random
print(math.sqrt(25))
print(math.ceil(4.56))
print(math.floor(4.46))
print(math.pi)
print(math.pow(2,3))

# Random module.
# Random float betwen 0 and 1
print(random.random())
print(random.randint(1,7))
