# for loop
# for loop is used to iterate over a sequence (like a list, tuple, 
# dictionary, set or string)
for x in range(5):
    print(x)

# 12-17
for y in range(12,18):
    print(y)

# Loop through a list.
students = ["Brian","Kelvin","Mary","William","Kamau"]
print(students)
for a in students:
    print(a)

# A list of fruits.
fruits = ["Mango","Banana","Oranges","Pineapple"]
for fruit in fruits:
    print(fruit)

# loop through a string.:
for z in "emobilis":
    print(z)