# While loop - iterates through a block of code as long as a given condition is true.
# Syntax
# While condition:
   # Block of code to be executed.

# Print Hello python 5 times.
x = 1
while x <= 5:
    print("Hello python")
    x += 1  # x=x+1

# Print numbers 0 - 7
y = 0
while y <= 7:
    print(y)
    y += 1

# Print numbers 20 - 30
z = 20
while z <= 30:
    print(z)
    if z == 25:
        break
    z += 1

